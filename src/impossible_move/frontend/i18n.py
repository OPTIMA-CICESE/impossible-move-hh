def normalize_language(language: str | None) -> str:
    value = (language or DEFAULT_LANGUAGE).lower().split("-")[0]
    return value if value in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def strings(language: str = DEFAULT_LANGUAGE) -> dict[str, str]:
    return dict(_TRANSLATIONS[normalize_language(language)])


def tr(key: str, language: str = DEFAULT_LANGUAGE, **values: object) -> str:
    language = normalize_language(language)
    template = _TRANSLATIONS[language].get(key) or _TRANSLATIONS[DEFAULT_LANGUAGE].get(key) or key
    if values:
        try:
            return template.format(**values)
        except (KeyError, ValueError):
            return template
    return template


