def localized_item_name(asset_id: str, original_name: str, language: str = DEFAULT_LANGUAGE) -> str:
    """Translate an item display name while preserving its optional occurrence suffix.

    Generated catalogs contain presentation labels such as ``Sofá 2``.  The
    mathematical trace only carries the stable item id/asset id, so changing
    language never alters or recomputes the run.
    """
    language = normalize_language(language)
    if language == "es":
        return original_name
    key = _OBJECT_KEY_BY_ASSET.get(asset_id, "object_generic")
    base = tr(key, language)
    match = re.search(r"\s+(\d+)\s*$", original_name)
    return f"{base} {match.group(1)}" if match else base
